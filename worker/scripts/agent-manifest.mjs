// Writes src/agents/claude-code.generated.ts: what the worker needs to
// install the Claude Code version its Agent SDK pins, taken at build time
// from the repository's package-lock.json (each platform package's tarball
// path and sha512 integrity) and from the installed SDK's package.json (the
// CLI version it bundles). The worker never looks this up at run time.
//
// Usage: node worker/scripts/agent-manifest.mjs (run by the worker's build,
// typecheck and test scripts). The file is rewritten only when it changes.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const worker = join(dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(readFileSync(join(worker, "..", "package-lock.json"), "utf8"));
const require = createRequire(join(worker, "package.json"));
const sdkName = "@anthropic-ai/claude-agent-sdk";
const sdkPackage = JSON.parse(readFileSync(join(dirname(require.resolve(sdkName)), "package.json"), "utf8"));

function fail(message) {
  console.error(`agent-manifest: ${message}`);
  process.exit(1);
}

const sdkEntry = lock.packages?.[`node_modules/${sdkName}`];
if (!sdkEntry) fail(`${sdkName} is missing from package-lock.json`);
if (sdkEntry.version !== sdkPackage.version) {
  fail(`installed ${sdkName} ${sdkPackage.version} differs from package-lock.json ${sdkEntry.version}; run npm ci`);
}
const version = sdkPackage.claudeCodeVersion;
if (typeof version !== "string" || !/^\d+\.\d+\.\d+$/.test(version)) fail(`${sdkName} has no claudeCodeVersion`);

// Node's process.platform-process.arch, with -musl for musl Linux.
const platforms = ["linux-x64", "linux-arm64", "linux-x64-musl", "linux-arm64-musl", "darwin-x64", "darwin-arm64"];
const artifacts = {};
for (const platform of platforms) {
  const name = `${sdkName}-${platform}`;
  const entry = lock.packages?.[`node_modules/${name}`];
  if (!entry) fail(`${name} is missing from package-lock.json`);
  if (entry.version !== sdkPackage.version) fail(`${name} ${entry.version} differs from ${sdkName} ${sdkPackage.version}`);
  if (typeof entry.integrity !== "string" || !/^sha512-[A-Za-z0-9+/]{86}==$/.test(entry.integrity)) {
    fail(`${name} has no sha512 integrity`);
  }
  let path;
  try {
    path = new URL(entry.resolved).pathname;
  } catch {
    fail(`${name} has no resolved URL`);
  }
  if (!path.endsWith(".tgz")) fail(`${name} resolves to ${path}, not a tarball`);
  artifacts[platform] = { package: name, path, integrity: entry.integrity };
}

const text = `// Generated by worker/scripts/agent-manifest.mjs from package-lock.json; do not edit.

/** The Claude Code version the pinned Agent SDK (${sdkPackage.version}) bundles: the only one this worker runs. */
export const CLAUDE_CODE_VERSION = ${JSON.stringify(version)};

/** Per platform (process.platform-process.arch, -musl on musl Linux): the npm tarball and its digest. */
export const CLAUDE_CODE_ARTIFACTS: Readonly<Record<string, { package: string; path: string; integrity: string }>> = ${JSON.stringify(artifacts, null, 2)};
`;
const out = join(worker, "src", "agents", "claude-code.generated.ts");
let old = "";
try {
  old = readFileSync(out, "utf8");
} catch {
  // Not generated yet.
}
if (old !== text) writeFileSync(out, text);
